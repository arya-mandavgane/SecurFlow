from django.db import models
from django.conf import settings

class VerificationRecord(models.Model):
    class Status(models.TextChoices):
        PENDING = 'PENDING', 'Pending Review'
        APPROVED = 'APPROVED', 'Approved / Verified'
        REJECTED = 'REJECTED', 'Rejected'
        CLARIFICATION_REQUESTED = 'CLARIFICATION_REQUESTED', 'Clarification Requested'

    fdr = models.ForeignKey(
        'fdrs.FDR',
        on_delete=models.CASCADE,
        related_name='verification_records',
        help_text="FDR under verification"
    )
    official = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        null=True,
        blank=True,
        on_delete=models.SET_NULL,
        related_name='verifications',
        help_text="AICTE official conducting or assigning verification"
    )
    status = models.CharField(
        max_length=30,
        choices=Status.choices,
        default=Status.PENDING
    )
    remarks = models.TextField(blank=True, help_text="Official verification comments or reason for clarification/rejection")
    mismatches = models.JSONField(
        default=list,
        blank=True,
        help_text="List of flagged mismatches between submitted data and OCR extraction"
    )
    is_automated_draft = models.BooleanField(
        default=False,
        help_text="Whether this draft record was auto-generated by the OCR processing pipeline"
    )
    timestamp = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ['-timestamp']
        verbose_name = 'Verification Record'
        verbose_name_plural = 'Verification Records'

    def __str__(self):
        return f"Verification for FDR #{self.fdr.fdr_number} - {self.get_status_display()}"
